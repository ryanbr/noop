final class SleepRecalculationDependentsTests: XCTestCase {
    private func rows(hrv: Double) -> [DailyMetric] {
        var result: [DailyMetric] = []
        for i in 0..<31 {
            let day = String(format: "2026-07-%02d", i + 1)
            let value: Double = i == 19 ? hrv : Double(45 + (i % 7) * 3)
            let resp: Double = 15.0 + Double(i % 4) * 0.2
            let skin: Double = 33.0 + Double(i % 3) * 0.1
            result.append(DailyMetric(day: day, totalSleepMin: 420, efficiency: 0.9,
                deepMin: 90, remMin: 100, lightMin: 230, disturbances: 1, restingHr: 48 + i % 5,
                avgHrv: value, recovery: -1, strain: 10, exerciseCount: 0, respRateBpm: resp, skinTempC: skin))
        }
        return result
    }

    private func updates(hrv: Double, refresh: Bool, selected: String = "2026-07-20") -> [SleepRecoveryUpdate] {
        SleepRecalculationDependents.updates(selectedDay: selected, anchorDay: "2026-07-31", refreshBaseline: refresh,
            imported: [], computed: rows(hrv: hrv), sourceByDay: [:], importedSource: "my-whoop",
            hrvEpoch: 0, recoveryEpoch: 0)
    }

    func testOnlyTheExistingRecentBaselineWindowCanChange() {
        let result = updates(hrv: 80, refresh: true)
        XCTAssertEqual(result.map(\.day), (11...31).map { String(format: "2026-07-%02d", $0) })
        XCTAssertTrue(updates(hrv: 80, refresh: true, selected: "2026-07-01").isEmpty)
        XCTAssertTrue(updates(hrv: 80, refresh: true, selected: "2026-08-01").isEmpty)
    }

    func testUnchangedBaselineInputsRefreshOnlySelectedCharge() {
        XCTAssertEqual(updates(hrv: 80, refresh: false).map(\.day), ["2026-07-20"])
        XCTAssertNotEqual(updates(hrv: 20, refresh: true), updates(hrv: 120, refresh: true))
    }

